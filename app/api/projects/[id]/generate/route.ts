import { NextResponse } from "next/server";
import { database, projectById } from "@/lib/db";
import { makeScript } from "@/lib/content";
import { generateAiText } from "@/lib/ai";

export const runtime = "nodejs";
type Context = { params: Promise<{ id: string }> };

export async function POST(request: Request, { params }: Context) {
  const { id } = await params;
  const project = projectById(id);
  if (!project) return NextResponse.json({ error: "Project not found." }, { status: 404 });
  const body = await request.json().catch(() => ({}));
  const topic = typeof body.topic === "string" ? body.topic.slice(0, 2000) : project.topic;
  const uploadedSource = typeof body.source === "string" ? body.source.slice(0, 8000) : "";
  const source = [uploadedSource, project.repo_summary].filter(Boolean).join("\n\n").slice(0, 12000);
  let script: string;
  let mode = "offline-template";
  try {
    if (process.env.AI_PROVIDER && process.env.AI_PROVIDER !== "template") {
      const result = await generateAiText(
        "You are a video scriptwriter. Write a concise, accurate script with a hook, clearly labeled scenes, and a closing. Do not invent facts that are not in the supplied source.",
        `Topic or brief: ${topic}\nSource text (if provided): ${source}\nCreate a useful video script.`,
      );
      script = result.text;
      mode = result.mode;
    } else {
      script = makeScript(topic, source);
    }
  } catch (error) {
    return NextResponse.json({ error: error instanceof Error ? error.message : "The configured AI provider failed." }, { status: 502 });
  }
  const now = new Date().toISOString();
  database().prepare("UPDATE projects SET topic = ?, script = ?, updated_at = ? WHERE id = ?").run(topic, script, now, id);
  return NextResponse.json({ mode, notice: mode === "offline-template" ? "Generated with an offline writing template; this is not an AI model." : `Script generated by ${mode}.`, script });
}
